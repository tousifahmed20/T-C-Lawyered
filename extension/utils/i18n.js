/** All messages for a language code, English-filled for any missing keys. */
export function getMessages(code) {
  return { ...EN, ...(UI[code] || {}) };
}

/** A single translated string, English fallback. */
export function t(code, key) {
  return UI[code]?.[key] ?? EN[key] ?? key;
}
